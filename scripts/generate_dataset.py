# ── Assemble DataFrame ──────────────────────────────────────────────────────
rows = []
for label, qs in QUESTIONS.items():
    for q in qs:
        rows.append({
            "text":       q.strip(),
            "label":      label,
            "source":     "synthetic",
            "language":   "en",
        })

new_df = pd.DataFrame(rows)

# ── Merge with existing ─────────────────────────────────────────────────────
existing_path = Path("reports/tables/processed_questions.csv")
if existing_path.exists():
    old_df = pd.read_csv(existing_path)
    combined = pd.concat([old_df, new_df], ignore_index=True)
else:
    combined = new_df

# Deduplicate on cleaned text (lowercase, no punct)
combined["_key"] = combined["text"].str.lower().str.replace(r"[^a-z\s]", "", regex=True).str.strip()
combined = combined.drop_duplicates(subset="_key").drop(columns="_key")
combined = combined.reset_index(drop=True)

# Regenerate text_clean if column exists or add it
import re as _re
def _clean(t):
    t = t.lower()
    t = _re.sub(r"[^a-z\s]", " ", t)
    return " ".join(t.split())

combined["text_clean"] = combined["text"].apply(_clean)

# ── Save ────────────────────────────────────────────────────────────────────
existing_path.parent.mkdir(parents=True, exist_ok=True)
combined.to_csv(existing_path, index=False)

